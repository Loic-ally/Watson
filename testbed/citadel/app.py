@app.route("/robots.txt")
def robots():
    return Response("User-agent: *\nDisallow: /admin/report\nDisallow: /preview\n",
                    mimetype="text/plain")


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        u = request.form.get("username", "")
        p = request.form.get("password", "")
        q = "SELECT * FROM users WHERE username='%s' AND password='%s'" % (u, p)
        try:
            row = db().execute(q).fetchone()
        except sqlite3.Error as e:
            return Response("query error: " + str(e), status=500)
        if row:
            session["user"] = row["username"]
            session["role"] = row["role"]
            return redirect("/admin/report?name=Q3")
        return Response("Invalid credentials", status=401)
    return Response('<form method="post"><input name="username">'
                    '<input name="password" type="password"><button>Sign in</button></form>',
                    mimetype="text/html")


@app.route("/admin/report")
def report():  # admin-only; template injection in the report title
    if session.get("role", "").strip() != "admin":
        return Response("forbidden — admin session required", status=403)
    name = request.args.get("name", "Untitled")
    return render_template_string("<h1>Report: " + name + "</h1><p>Generated by Citadel.</p>")


@app.route("/preview")
def preview():  # SSRF (secondary finding / red herring)
    url = request.args.get("url", "")
